import { expect, test } from "bun:test";

import { docFormats } from "./doc-formats";

const fixture = (path: string) => Bun.file(`${import.meta.dir}/../../fixtures/${path}`).text();
const outsideCode = (blocks: string[]) =>
  blocks.filter((block) => !block.startsWith("```")).join("\n");
const blocksOf = (doc: ReturnType<typeof docFormats.mdx.parse>) =>
  doc.sections.flatMap((section) => section.blocks);

test("mdx: front matter, title, description and the section tree", async () => {
  const doc = docFormats.mdx.parse(await fixture("mdx/server.mdx"), "runtime/http/server.mdx");
  expect(doc.title).toBe("Server");
  expect(doc.description).toBe("Use `Bun.serve` to start a high-performance HTTP server in Bun");
  expect(doc.sections.map((s) => [s.path, s.depth])).toEqual([
    [["Server"], 0],
    [["Server", "Basic Setup"], 2],
    [["Server", "Options"], 2],
    [["Server", "Options", "Tables"], 3],
  ]);
  expect(doc.sections[0]!.blocks).toEqual([]);
});

test("mdx: imports, comments, JSX wrappers and link targets are gone, text stays", async () => {
  const doc = docFormats.mdx.parse(await fixture("mdx/server.mdx"), "runtime/http/server.mdx");
  const text = outsideCode(blocksOf(doc));
  for (const gone of ["import Intro", "Generated by", "<Note", "<Tab", "<ParamField", "<br", "{"]) {
    expect(text).not.toContain(gone);
  }
  expect(text).not.toContain("](");
  expect(text).toContain("Routes need Bun v1.2.3+.");
  expect(text).toContain("Install with `npm`.");
  expect(text).toContain("Install with `bun`.");
  expect(text).toContain("routing");
  expect(text).toContain("`bun run`");
  expect(text).toContain("Start with `bun run` and a break.");
});

test("mdx: ParamField attributes become a line before its text", async () => {
  const doc = docFormats.mdx.parse(await fixture("mdx/server.mdx"), "runtime/http/server.mdx");
  const options = doc.sections.find((s) => s.path.join(">") === "Server>Options")!.blocks;
  expect(options.slice(0, 4)).toEqual([
    "`port` (number)",
    "The port to listen on.",
    "`hostname` (string)",
    "The hostname to bind. See TLS.",
  ]);
});

test("mdx: a code block is kept byte for byte, including JSX and import text inside it", async () => {
  const doc = docFormats.mdx.parse(await fixture("mdx/server.mdx"), "runtime/http/server.mdx");
  const code = blocksOf(doc).find((block) => block.startsWith("```ts"))!;
  expect(code).toBe(
    [
      '```ts title="index.ts" icon="/icons/typescript.svg"',
      'import { serve } from "bun";',
      'const jsx = <Foo bar="baz" />;',
      "",
      "const server = Bun.serve({",
      "  routes: {",
      '    "/api/status": new Response("OK"),',
      "  },",
      "});",
      "```",
    ].join("\n"),
  );
});

test("mdx: a table is one block", async () => {
  const doc = docFormats.mdx.parse(await fixture("mdx/server.mdx"), "runtime/http/server.mdx");
  const tables = doc.sections.find((s) => s.path.at(-1) === "Tables")!.blocks;
  expect(tables).toHaveLength(1);
  expect(tables[0]).toContain("| `port`");
});

test("mdx: internal links come out corpus-relative, external and anchor-only ones are dropped", async () => {
  const doc = docFormats.mdx.parse(await fixture("mdx/server.mdx"), "runtime/http/server.mdx");
  expect(doc.links).toEqual(["runtime/http/routing", "runtime/bun-apis", "runtime/http/tls.mdx"]);
});

test("mdx: an h1 equal to the title merges into the root section, a heading id is stripped", async () => {
  const doc = docFormats.mdx.parse(await fixture("mdx/guide.mdx"), "runtime/guide.mdx");
  expect(doc.title).toBe("Guide");
  expect(doc.sections.map((s) => [s.path, s.depth])).toEqual([
    [["Guide"], 0],
    [["Guide", "Connecting to an already-running Chrome"], 4],
    [["Guide", "Guide"], 2],
  ]);
  expect(doc.sections[0]!.blocks[0]).toBe("Intro text with a relative link and a parent link.");
  expect(doc.sections[1]!.blocks).toEqual(["Details here."]);
  expect(doc.links).toEqual(["runtime/server.mdx", "pm/cli.mdx"]);
});

test("mdx: malformed MDX throws with the file path", () => {
  expect(() => docFormats.mdx.parse("Hello {broken", "docs/bad.mdx")).toThrow("docs/bad.mdx");
});

test("jekyll: front matter, blurb as description, no Liquid or HTML left", async () => {
  const doc = docFormats.jekyll.parse(
    await fixture("jekyll/introduction.md"),
    "sql/introduction.md",
  );
  expect(doc.title).toBe("SQL Introduction");
  expect(doc.description).toBe("A short introduction to SQL.");
  const text = outsideCode(blocksOf(doc));
  for (const gone of ["{%", "redirect_from", "layout", "<div", "monospace_table", "tooltip"]) {
    expect(text).not.toContain(gone);
  }
  expect(text).toContain("Literal `{{ braces }}` stay.");
  expect(text).toContain("A blog post: CSV sniffer.");
  expect(doc.sections.map((s) => s.path)).toEqual([
    ["SQL Introduction"],
    ["SQL Introduction", "Concepts"],
    ["SQL Introduction", "Example"],
    ["SQL Introduction", "Example", "Details"],
  ]);
});

test("jekyll: Liquid link targets, queries, anchors and relative links resolve; blog and external links drop", async () => {
  const doc = docFormats.jekyll.parse(
    await fixture("jekyll/introduction.md"),
    "sql/introduction.md",
  );
  expect(doc.links).toEqual([
    "sql/dialect/postgresql_compatibility.md",
    "installation.html",
    "sql/statements/select.md",
    "sql/overview.md",
  ]);
});

test("jekyll: code blocks keep Liquid-looking text, and highlighted HTML becomes a code block", async () => {
  const doc = docFormats.jekyll.parse(
    await fixture("jekyll/introduction.md"),
    "sql/introduction.md",
  );
  const blocks = doc.sections.find((s) => s.path.at(-1) === "Example")!.blocks;
  expect(blocks).toEqual([
    "```sql\nSELECT '{% link docs/2.0/not-a-link.md %}' AS kept;\n```",
    "```c\nint x = 1; // a < b\n```",
  ]);
});

test("jekyll: the select fixture nests sections and keeps both SQL blocks", async () => {
  const doc = docFormats.jekyll.parse(
    await fixture("jekyll/select.md"),
    "sql/statements/select.md",
  );
  expect(doc.sections.map((s) => s.path.join(" > "))).toEqual([
    "SELECT Statement",
    "SELECT Statement > Syntax",
    "SELECT Statement > WHERE Clause",
    "SELECT Statement > WHERE Clause > Examples",
  ]);
  expect(doc.links).toEqual(["sql/introduction.md"]);
  expect(doc.sections[3]!.blocks).toEqual([
    "Filter by a column:",
    "```sql\nSELECT * FROM tbl WHERE id = 1;\n```",
  ]);
});

test("inline HTML is dropped and its text kept", () => {
  const doc = docFormats.jekyll.parse("Press <kbd>Ctrl</kbd> now.", "a.md");
  expect(doc.sections[0]!.blocks).toEqual(["Press Ctrl now."]);
});

test("the title falls back to the first h1, then to the file name", () => {
  const h1 = docFormats.jekyll.parse("# Hello\n\ntext", "a/b.md");
  expect(h1.title).toBe("Hello");
  expect(h1.sections).toEqual([{ path: ["Hello"], depth: 0, blocks: ["text"] }]);
  expect(docFormats.jekyll.parse("text only", "a/b-c.md").title).toBe("b-c");
});

test("empty, anchor-only, external, protocol-relative and out-of-corpus targets are not links", () => {
  const doc = docFormats.jekyll.parse(
    "[a](#x) [b](https://x.y) [c](mailto:a@b.c) [d](//cdn.x/y) [e]() [f](other.md?x=1#y) [g](../../x.md)",
    "top/page.md",
  );
  expect(doc.links).toEqual(["top/other.md"]);
});

test("a repeated link target is recorded once", () => {
  const doc = docFormats.jekyll.parse("[a](/x.md) and [b](/x.md)", "p.md");
  expect(doc.links).toEqual(["x.md"]);
});

test("each format names the extensions it reads", () => {
  expect(docFormats.mdx.extensions).toEqual([".mdx"]);
  expect(docFormats.jekyll.extensions).toEqual([".md"]);
});

test("jekyll: a code fence right after an HTML block is not swallowed by it", () => {
  const doc = docFormats.jekyll.parse(
    "<details>\n<summary markdown='span'>\nClick\n</summary>\n```text\nline1\nline2\n\nline3\n```\n</details>\n",
    "a.md",
  );
  expect(doc.sections[0]!.blocks).toEqual(["```text\nline1\nline2\n\nline3\n```"]);
});

test("a very long line does not make the heading-id or the HTML pass quadratic", () => {
  const started = performance.now();
  docFormats.mdx.parse(`# a${" ".repeat(200_000)}\n\ntext\n`, "a.mdx");
  const html = `<pre><code>${"<".repeat(200_000)}</code></pre>\n`;
  expect(docFormats.jekyll.parse(html, "b.md").sections[0]!.blocks).toHaveLength(1);
  expect(performance.now() - started).toBeLessThan(2000);
});

test("a trailing heading id is still dropped, with the space before it", () => {
  const doc = docFormats.mdx.parse("# T\n\n## Setup {#setup}  \n\ntext\n", "a.mdx");
  expect(doc.sections.map((s) => s.path.at(-1))).toEqual(["T", "Setup"]);
});
